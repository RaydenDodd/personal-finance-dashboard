"""Consume durable backend notifications after manual or scheduled bank syncs."""
import json
import subprocess
from operations import Api, classify

KEY='finance:local-categorization:pending:1'
def redis(*args):
    return subprocess.check_output(['docker','exec','personal-finance-dashboard-redis-1','redis-cli',*args],text=True,timeout=20).strip()

def main():
    generation=redis('GET',KEY)
    if not generation:return
    with Api() as api:
        status=api.request('/bank-data-providers/sync/status')
        if any(row.get('status') in ('syncing','queued') for row in status.get('accounts',[])):
            print('Bank sync still active; categorization deferred')
            return
        result=classify(api)
    # Do not erase a notification generated by a newer sync during classification.
    redis('EVAL',"if redis.call('GET',KEYS[1])==ARGV[1] then return redis.call('DEL',KEYS[1]) else return 0 end",'1',KEY,generation)
    print(json.dumps({'postSyncCategorization':result}))

if __name__=='__main__':main()
